#!/usr/bin/env python3
"""Build ds/tokens.json from ds/tokens.css (the CSS is the source of truth).

Each token → { "value": as written, "resolved": var() chains resolved, "note": trailing comment }.
Scripts and charts (research/charts, deck data viz) read the resolved values.
Usage: python3 ds/tools/tokens_json.py
"""
import json, os, re

DS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
css = open(os.path.join(DS, 'tokens.css')).read()
root = css.split('@media')[0]

tokens = {}
for m in re.finditer(r'(--[\w-]+)\s*:\s*([^;]+);[ \t]*(?:/\*\s*(.*?)\s*\*/)?', root):
    name, value, note = m.group(1), m.group(2).strip(), (m.group(3) or '').strip()
    tokens.setdefault(name, {'value': value, 'note': note})


def resolve(v, depth=0):
    if depth > 12:
        return v
    return re.sub(r'var\((--[\w-]+)\)', lambda m: resolve(tokens[m.group(1)]['value'], depth + 1)
                  if m.group(1) in tokens else m.group(0), v)


for t in tokens.values():
    t['resolved'] = resolve(t['value'])

group = lambda n: ('raw' if re.match(r'--color-(gray|primary|secondary|success|error|warning|blue|orange)-\d+$', n)
                   else 'role')
out = {
    '$source': 'ds/tokens.css (generated by ds/tools/tokens_json.py, do not edit by hand)',
    'tokens': {n: {**t, 'layer': group(n)} for n, t in tokens.items()},
}
json.dump(out, open(os.path.join(DS, 'tokens.json'), 'w'), indent=1, ensure_ascii=False)
print(f'{len(tokens)} tokens → ds/tokens.json')
