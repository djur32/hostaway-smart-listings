#!/usr/bin/env python3
"""Build ds/icons/sprite.svg from ds/icons/*.svg (Tabler outline, MIT) + ds/channels/*.svg.

- Tabler icons become <symbol id="i-NAME">; the hard-coded stroke-width="2" is removed so
  CSS sets it (Hospitable's glyphs read as ~1.5px at 24px → .icon { stroke-width: 1.5 }).
- Channel marks become <symbol id="ch-NAME"> and keep their own colours.
- Badge glyphs (ds/channels/glyph) become <symbol id="chg-NAME">, drawn in currentColor for the white-on-brand badge.
Usage: python3 ds/tools/build_icons.py
"""
import os, re

DS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
       '<!-- Icons: Tabler Icons (MIT, tabler.io) outline set. Channel marks: see ds/channels/README.md -->']
for folder, prefix in (('icons', 'i-'), ('channels', 'ch-'), ('channels/glyph', 'chg-')):
    for f in sorted(os.listdir(os.path.join(DS, folder))):
        if not f.endswith('.svg') or f == 'sprite.svg':
            continue
        src = open(os.path.join(DS, folder, f)).read()
        vb = re.search(r'viewBox="([^"]+)"', src).group(1)
        inner = re.search(r'<svg[^>]*>(.*)</svg>', src, re.S).group(1)
        inner = re.sub(r'<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>', '', inner)
        inner = re.sub(r'<title>.*?</title>', '', inner)
        inner = re.sub(r'\s+', ' ', inner).strip()
        out.append(f'<symbol id="{prefix}{f[:-4]}" viewBox="{vb}">{inner}</symbol>')
out.append('</svg>')
svg_text = '\n'.join(out) + '\n'
open(os.path.join(DS, 'icons', 'sprite.svg'), 'w').write(svg_text)
# sprite.js — injects the sprite so pages work from file:// (external <use> is blocked there)
import json
open(os.path.join(DS, 'icons', 'sprite.js'), 'w').write(
    '/* generated by ds/tools/build_icons.py */\n'
    '(function(){var s=' + json.dumps(svg_text) + ';'
    'function go(){document.body.insertAdjacentHTML("afterbegin",s);}'
    'if(document.body)go();else document.addEventListener("DOMContentLoaded",go);})();\n')
print(f'{len(out) - 3} symbols → ds/icons/sprite.svg')
