#!/usr/bin/env node
/* ============================================================================
   SYNC-DS · the one door between the design system and the deck.

     node tools/sync-ds.mjs        (build.mjs runs it first, every time)

   The deck links src/kit/ds/tokens.css and nothing else from the design system
   (kit/tokens.css imports it into the lowest cascade layer). This copies
   ../ds/tokens.css (the repo's design system, owned by S02) there, byte for byte,
   with a one-line header, so the deck never holds a hand-copied value and dist/ and
   the Vercel build (which serve deck/ alone) still have the tokens. When ds/ is not
   next to the deck (a deck-only checkout), the last synced copy is kept.
   Never edit src/kit/ds/tokens.css by hand.

   History: S07 started before S02 shipped and ran on a provisional file of colours
   sampled from the screenshots. S02's tokens landed the same day and replaced it;
   the provisional file is gone (deck/DECISIONS.md, D-071).
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const DS = path.resolve(ROOT, '../ds/tokens.css');
const OUT = path.join(ROOT, 'src/kit/ds/tokens.css');

export function syncDs() {
  const real = fs.existsSync(DS);
  if (!real) {
    if (!fs.existsSync(OUT)) throw new Error(`sync-ds: ${DS} not found and no synced copy at ${OUT}`);
    const kept = fs.readFileSync(OUT, 'utf8');
    return { source: 'kept', tokens: new Set([...kept.matchAll(/(--[a-z0-9-]+)\s*:/g)].map((m) => m[1])) };
  }
  const body = fs.readFileSync(DS, 'utf8');
  const out = `/* GENERATED by deck/tools/sync-ds.mjs from ds/tokens.css (S02). Do not edit. */\n` + body;
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev !== out) { fs.mkdirSync(path.dirname(OUT), { recursive: true }); const tmp = OUT + '.' + process.pid + '.tmp'; fs.writeFileSync(tmp, out); fs.renameSync(tmp, OUT); }
  /* S02's file may @import siblings (fonts, a json twin is ignored): copy any relative
     url() or @import target next to it so the deck keeps resolving them. */
  if (real) {
    for (const [, rel] of body.matchAll(/(?:@import\s+(?:url\()?|url\()\s*["']?([^"')\s]+)["']?/g)) {
      if (/^(data:|https?:|\/)/.test(rel)) continue;
      const src = path.resolve(path.dirname(DS), rel), dest = path.resolve(path.dirname(OUT), rel);
      if (fs.existsSync(src) && fs.statSync(src).isFile()) { fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.copyFileSync(src, dest); }
    }
  }
  /* S02's components (class prefix h-, no global rules) and its icon + channel-mark sprite */
  for (const [from, to] of [['components.css', 'components.css'], ['icons/sprite.js', 'sprite.js']]) {
    const a = path.resolve(ROOT, '../ds', from), b = path.join(path.dirname(OUT), to);
    if (!fs.existsSync(a)) continue;
    const txt = (to.endsWith('.css') ? `/* GENERATED by deck/tools/sync-ds.mjs from ds/${from} (S02). Do not edit. */\n` : `/* GENERATED by deck/tools/sync-ds.mjs from ds/${from} (S02). Do not edit. */\n`) + fs.readFileSync(a, 'utf8');
    if (!fs.existsSync(b) || fs.readFileSync(b, 'utf8') !== txt) fs.writeFileSync(b, txt);
  }
  /* S02's illustrations, for the stage openers: copied next to the deck's own art */
  const ILLO = path.resolve(ROOT, '../ds/illustrations'), ILLO_OUT = path.join(ROOT, 'src/assets/illustrations');
  if (fs.existsSync(ILLO)) for (const f of fs.readdirSync(ILLO).filter((x) => x.endsWith('.svg'))) {
    fs.mkdirSync(ILLO_OUT, { recursive: true });
    const a = path.join(ILLO, f), b = path.join(ILLO_OUT, f);
    if (!fs.existsSync(b) || fs.readFileSync(a, 'utf8') !== fs.readFileSync(b, 'utf8')) fs.copyFileSync(a, b);
  }
  /* the list of drawings that exist, so a cover never asks for one that doesn't (kit/hc.js) */
  fs.mkdirSync(ILLO_OUT, { recursive: true });
  const have = fs.readdirSync(ILLO_OUT).filter((x) => x.endsWith('.svg')).map((x) => x.replace(/\.svg$/, '')).sort();
  const idx = path.join(ILLO_OUT, 'index.json'), txt = JSON.stringify(have) + '\n';
  if (!fs.existsSync(idx) || fs.readFileSync(idx, 'utf8') !== txt) fs.writeFileSync(idx, txt);
  return { source: 'ds', tokens: new Set([...body.matchAll(/(--[a-z0-9-]+)\s*:/g)].map((m) => m[1])) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const r = syncDs();
  console.log(`src/kit/ds/tokens.css ← ${r.source === 'ds' ? 'ds/tokens.css' : 'the last synced copy (ds/ not found)'} (${r.tokens.size} tokens)`);
}
